#!/usr/bin/env python
"""Smoke-test: verify InterModalBiMamba on CPU.

Generated by Claude Sonnet 4.6

Checks:
1. P is doubly stochastic (rows and columns sum to 1)
2. Output shape is correct (B, L', MC')
3. Equivariance: permuting input modalities does not change the output

Usage (from repo root):
    python tests/test_inter_modal.py
"""

from __future__ import annotations

import jax
import jax.numpy as jnp
import numpy as np
import sys

from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from inter_modal import InterModalBiMamba
from read_data import log


def main() -> None:
    B, Lp, Cp, M = 2, 250, 128, 8  # 4 modalities x 2 roles
    D = M * Cp  # MC' = 1024 (output width); the block itself runs at width C'

    rng = jax.random.PRNGKey(95)
    rng_init, rng_gumbel, rng_data = jax.random.split(rng, 3)

    # Fake hiddens dict
    keys = [f"expert.mod{i}" for i in range(M // 2)] + [f"novice.mod{i}" for i in range(M // 2)]
    keys = sorted(keys)
    hiddens = {k: jax.random.normal(jax.random.fold_in(rng_data, i), (B, Lp, Cp)) for i, k in enumerate(keys)}

    model = InterModalBiMamba(D=Cp, N=16, D_C=4, GS_dim=64, n_iters=20)

    variables = model.init(rng_init, hiddens, tau=1.0, rng=rng_gumbel, train=False)
    param_count = sum(x.size for x in jax.tree.leaves(variables["params"]))
    log.info(f"InterModalBiMamba params: {param_count:,}")

    # Forward pass
    H, updates = model.apply(variables, hiddens, tau=1.0, rng=rng_gumbel, train=False, mutable=["batch_stats"])
    log.info(f"Output shape: {H.shape}  (expected ({B}, {Lp}, {D}))")
    assert H.shape == (B, Lp, D), f"Shape mismatch: {H.shape}"

    # Check P is doubly stochastic
    gs_vars = {"params": {k: v for k, v in variables["params"].items() if "gumbel_sinkhorn" in k}}
    # Extract P by running just the GumbelSinkhorn submodule
    from inter_modal import GumbelSinkhorn, sinkhorn
    stacked = jnp.stack([hiddens[k] for k in keys], axis=1)
    summaries = stacked.mean(axis=2)  # (B, M, C')
    gs = GumbelSinkhorn(M=M, d_key=64, n_iters=10)
    gs_variables = gs.init(rng_init, summaries, tau=1.0, rng=rng_gumbel)
    P = gs.apply(gs_variables, summaries, tau=1.0, rng=rng_gumbel)
    row_sums = P.sum(axis=-1)
    col_sums = P.sum(axis=-2)
    log.info(f"P row sums max error: {jnp.abs(row_sums - 1.0).max():.6f}")
    log.info(f"P col sums max error: {jnp.abs(col_sums - 1.0).max():.6f}")
    assert jnp.abs(row_sums - 1.0).max() < 1e-3, "P rows don't sum to 1"
    assert jnp.abs(col_sums - 1.0).max() < 1e-3, "P cols don't sum to 1"

    # Fixed orders: P is a constant permutation matrix, no meta-network parameters, and P is read out via sow
    from inter_modal import FIXED_ORDERS, fixed_permutation
    _, inter = model.apply(variables, hiddens, tau=1.0, rng=None, train=False, mutable=["batch_stats", "intermediates"])
    assert inter["intermediates"]["P"][0].shape == (B, M, M), "learned P not sown"
    for name in FIXED_ORDERS:
        perm = fixed_permutation(keys, name)
        assert sorted(perm.tolist()) == list(range(M)), f"{name} is not a permutation"
        fixed = InterModalBiMamba(D=Cp, N=16, D_C=4, GS_dim=64, n_iters=20, fixed_order=name)
        fv = fixed.init(rng_init, hiddens, tau=1.0, rng=rng_gumbel, train=False)
        assert "gumbel_sinkhorn" not in fv["params"], f"{name}: meta-network should be absent"
        assert set(fv["params"]) == set(variables["params"]) - {"gumbel_sinkhorn"}, f"{name}: parameter tree differs"
        (Hf, inter) = fixed.apply(fv, hiddens, tau=0.3, rng=rng_gumbel, train=False, mutable=["batch_stats", "intermediates"])
        Pf = inter["intermediates"]["P"][0]
        assert jnp.all((Pf == 0) | (Pf == 1)) and jnp.all(Pf.sum(-1) == 1) and jnp.all(Pf.sum(-2) == 1), f"{name}: P not a permutation matrix"
        assert Hf.shape == (B, Lp, D)
        log.info(f"fixed order {name}: {[keys[j] for j in perm]}")
    interleaved = fixed_permutation(keys, "interleaved")
    assert [keys[j].split(".", 1)[1] for j in interleaved[:2]] == [keys[0].split(".", 1)[1]] * 2, "interleaved should pair roles"

    # Corrected layer: position queries + scaled scores + 50 Sinkhorn iterations + unsort
    fixed_model = InterModalBiMamba(D=Cp, N=16, D_C=4, GS_dim=64, n_iters=50, position_queries=True, scale_scores=True, unsort=True)
    cv = fixed_model.init(rng_init, hiddens, tau=1.0, rng=rng_gumbel, train=False)
    assert "position_queries" in cv["params"]["gumbel_sinkhorn"] and "query" not in cv["params"]["gumbel_sinkhorn"], "position queries not used"
    Hc, inter = fixed_model.apply(cv, hiddens, tau=0.3, rng=None, train=False, mutable=["batch_stats", "intermediates"])
    Pc = inter["intermediates"]["P"][0]
    log.info(f"corrected P: row-sum error {jnp.abs(Pc.sum(-1) - 1).max():.2e}, column-sum error {jnp.abs(Pc.sum(-2) - 1).max():.2e}")
    assert jnp.abs(Pc.sum(-1) - 1).max() < 1e-3 and jnp.abs(Pc.sum(-2) - 1).max() < 1e-3, "corrected P not doubly stochastic"
    assert Hc.shape == (B, Lp, D)

    # Position queries: renumbering the streams only renumbers the COLUMNS of P (P' = P R^T), so the slot contents are unchanged
    gs_pos = GumbelSinkhorn(M=M, d_key=64, n_iters=50, position_queries=True, scale_scores=True)
    gv = gs_pos.init(rng_init, summaries, tau=1.0)
    rho = jnp.array([3, 0, 7, 1, 6, 2, 5, 4])
    P1 = gs_pos.apply(gv, summaries, tau=0.5)
    P2 = gs_pos.apply(gv, summaries[:, rho], tau=0.5)
    assert jnp.allclose(P2, P1[:, :, rho], atol=1e-5), "position-query P does not follow the renumbering"
    assert jnp.allclose(jnp.einsum("bij,bjc->bic", P2, summaries[:, rho]), jnp.einsum("bij,bjc->bic", P1, summaries), atol=1e-4), "slot contents depend on numbering"

    # Unsort with a hard permutation returns every stream to its own slot: P^T (P u) = u
    perm = fixed_permutation(keys, "rand0")
    Ph = jnp.asarray(np.eye(M, dtype=np.float32)[perm])  # row i = one-hot of perm[i]
    u = jax.random.normal(rng_data, (M, Cp))
    assert jnp.allclose(Ph.T @ (Ph @ u), u), "P^T is not the inverse of P"

    # Probe order: scanning in the trained order changes nothing; another order changes the output but keeps its shape
    fo = InterModalBiMamba(D=Cp, N=16, D_C=4, GS_dim=64, n_iters=10, fixed_order="rand0")
    fv = fo.init(rng_init, hiddens, tau=1.0, rng=None, train=False)
    H_own = fo.apply(fv, hiddens, tau=1.0, rng=None, train=False)
    H_same = InterModalBiMamba(D=Cp, N=16, D_C=4, GS_dim=64, n_iters=10, fixed_order="rand0", probe_order="rand0").apply(fv, hiddens, tau=1.0, rng=None, train=False)
    H_other = InterModalBiMamba(D=Cp, N=16, D_C=4, GS_dim=64, n_iters=10, fixed_order="rand0", probe_order="blocked").apply(fv, hiddens, tau=1.0, rng=None, train=False)
    assert jnp.allclose(H_own, H_same, atol=1e-5), "probing the trained order changed the output"
    assert H_other.shape == H_own.shape and not jnp.allclose(H_own, H_other, atol=1e-4), "probe order had no effect"

    # A block with no state decay (A_bar = 1), no convolution and SHARED forward/backward parameters is order-equivariant:
    # forward prefix sum + backward suffix sum = total + own term, whatever the order. Checked on the raw scan.
    from ssm import ssm
    xs = jax.random.normal(rng_data, (1, M, 3))
    d = jnp.ones((1, M, 3)) * 0.5
    A0 = -jnp.full((3, 4), 1e-9)  # A_bar = exp(delta * A) ~ 1
    Bm = jax.random.normal(rng_init, (1, M, 4)); Cm = jax.random.normal(rng_gumbel, (1, M, 4))
    def bi(x, b, c):
        return ssm(x, d, A0, b, c) + jnp.flip(ssm(jnp.flip(x, 1), d, A0, jnp.flip(b, 1), jnp.flip(c, 1)), 1)
    perm = jnp.array(fixed_permutation(keys, "rand1"))
    assert jnp.allclose(bi(xs, Bm, Cm)[:, perm], bi(xs[:, perm], Bm[:, perm], Cm[:, perm]), atol=1e-4), "no-decay shared scan is not order-equivariant"

    log.info("All checks passed!")


if __name__ == "__main__":
    main()

